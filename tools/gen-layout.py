#!/usr/bin/env python3
"""Regenerates src/WomierDriver.Core/Device/Sk75TmrLayout.Keys.cs.

Inputs (checked in under docs/reverse-engineering/vendor/):
  * agk75b_ui_info.js   - key geometry of the vendor's "Common81_AGK75B" layout (used by the SK75 TMR)
  * sk75-layout.json    - decoded factory key matrix of the SK75 (slot -> HID usage)

Usage:  python tools/gen-layout.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI_INFO = ROOT / "docs" / "reverse-engineering" / "vendor" / "agk75b_ui_info.js"
MATRIX = ROOT / "docs" / "reverse-engineering" / "vendor" / "sk75-layout.json"
OUTPUT = ROOT / "src" / "WomierDriver.Core" / "Device" / "Sk75TmrLayout.Keys.cs"

CODE = {
    "ESC": "Escape", "GRAVE": "Backquote", "TAB": "Tab", "CAPSLOCK": "CapsLock", "LSHIFT": "ShiftLeft",
    "LCTRL": "ControlLeft", "LGUI": "MetaLeft", "LALT": "AltLeft", "SPACE": "Space", "MINUS": "Minus",
    "EQUAL": "Equal", "LBRACKET": "BracketLeft", "RBRACKET": "BracketRight", "BACKSLASH": "Backslash",
    "SEMICOLON": "Semicolon", "QUOTE": "Quote", "COMMA": "Comma", "PERIOD": "Period", "SLASH": "Slash",
    "RCTRL": "ControlRight", "RSHIFT": "ShiftRight", "LEFT": "ArrowLeft", "RIGHT": "ArrowRight", "UP": "ArrowUp",
    "DOWN": "ArrowDown", "DELETE": "Delete", "BACKSPACE": "Backspace", "ENTER": "Enter", "HOME": "Home",
    "END": "End", "PAGEUP": "PageUp", "PAGEDOWN": "PageDown",
}
LABEL = {
    "ESC": "Esc", "GRAVE": "`", "TAB": "Tab", "CAPSLOCK": "Caps", "LSHIFT": "Shift", "LCTRL": "Ctrl", "LGUI": "Win",
    "LALT": "Alt", "SPACE": "Space", "MINUS": "-", "EQUAL": "=", "LBRACKET": "[", "RBRACKET": "]", "BACKSLASH": "\\\\",
    "SEMICOLON": ";", "QUOTE": "'", "COMMA": ",", "PERIOD": ".", "SLASH": "/", "RCTRL": "Ctrl", "RSHIFT": "Shift",
    "LEFT": "←", "RIGHT": "→", "UP": "↑", "DOWN": "↓", "DELETE": "Del", "BACKSPACE": "Bksp",
    "ENTER": "Enter", "HOME": "Home", "END": "End", "PAGEUP": "PgUp", "PAGEDOWN": "PgDn",
}
SYMBOLS = {"GRAVE", "MINUS", "EQUAL", "LBRACKET", "RBRACKET", "BACKSLASH", "SEMICOLON", "QUOTE", "COMMA", "PERIOD", "SLASH"}
MODIFIERS = {"LCTRL", "LSHIFT", "LALT", "LGUI", "RCTRL", "RSHIFT"}
NAVIGATION = {"DELETE", "HOME", "END", "PAGEUP", "PAGEDOWN"}
ARROWS = {"UP", "DOWN", "LEFT", "RIGHT"}


def groups(name: str) -> str:
    g: list[str] = []
    if len(name) == 1 and name.isalpha():
        g.append("Letters")
    if name in ("W", "A", "S", "D"):
        g.append("Wasd")
    if len(name) == 1 and name.isdigit():
        g.append("Digits")
    if re.fullmatch(r"F\d{1,2}", name):
        g.append("FunctionRow")
    if name in MODIFIERS:
        g.append("Modifiers")
    if name in NAVIGATION:
        g.append("Navigation")
    if name in ARROWS:
        g.append("Arrows")
    if name in SYMBOLS:
        g.append("Symbols")
    if name == "Fn":
        g.append("Fn")
    return " | ".join("KeyGroup." + x for x in g) if g else "KeyGroup.None"


def main() -> int:
    ui = UI_INFO.read_text(encoding="utf-8")
    geometry = {
        m[0]: (int(m[1]), int(m[2]), int(m[3]), int(m[4]))
        for m in re.findall(r'(\w+): \{ x: (\d+), y: (\d+), width: (\d+), height: (\d+), type: "key"', ui)
    }
    slots = json.loads(MATRIX.read_text(encoding="utf-8"))["decoded_base_slots"]

    rows = []
    for s in slots:
        name = s.get("name")
        hid = s.get("hid") or 0
        if s["type"] == "advanced" and s.get("bytes") == [10, 1, 0, 0]:
            name, code, label = "Fn", "Fn", "Fn"
        else:
            code = CODE.get(name) or (("Digit" + name) if name.isdigit() else (("Key" + name) if len(name) == 1 else name))
            label = LABEL.get(name, name)
        x, y, w, h = geometry[code]
        rows.append((s["index"], hid, code, label, x, y, w, h, groups(name)))

    assert len(rows) == 81, f"expected 81 keys, got {len(rows)}"
    assert len({r[2] for r in rows}) == 81, "duplicate key codes"

    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen-layout.py from the vendor layout tables (AGK75B key geometry + SK75 factory key matrix).",
        "// Slot = index in the 128-entry key matrix, HidUsage = USB HID keyboard usage of the factory keymap,",
        "// Code = W3C KeyboardEvent.code name, geometry is in layout units on a 732 x 281 canvas.",
        "// </auto-generated>",
        "namespace WomierDriver.Core.Device;",
        "",
        "public static partial class Sk75TmrLayout",
        "{",
        "    private static KeyDefinition[] BuildKeys() =>",
        "    [",
    ]
    for r in sorted(rows):
        lines.append(f'        new({r[0]}, 0x{r[1]:02X}, "{r[2]}", "{r[3]}", {r[4]}, {r[5]}, {r[6]}, {r[7]}, {r[8]}),')
    lines += ["    ];", "}", ""]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(rows)} keys)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
